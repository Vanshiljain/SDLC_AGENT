import { z } from 'zod';
import { BRAND, ToolError } from '@forgeline/shared';
import { defineTool, idempotencyMarker, type AnySdlcTool } from '../core/tool';
import { NotionClient } from './client';

export const notionCreatePage = defineTool({
  name: 'notion.createPage',
  title: 'Create Notion page',
  description: 'Publish Markdown documentation as a Notion page under the project parent page (idempotent).',
  category: 'notion',
  provider: 'NOTION',
  agent: 'docs',
  inputSchema: z.object({
    parentPageId: z.string().optional(),
    parentDatabaseId: z.string().optional(),
    title: z.string().min(1).max(200),
    markdown: z.string().min(1).max(500_000),
    icon: z.string().max(4).optional(),
  }),
  permission: 'docs:write',
  risk: 'write',
  sideEffects: true,
  async execute(input, ctx) {
    const notion = await ctx.clients.notion();
    const parentPageId = input.parentPageId ?? (input.parentDatabaseId ? undefined : ctx.project?.settings.notionParentPageId);
    if (!parentPageId && !input.parentDatabaseId) {
      throw new ToolError('not_configured', 'No Notion parent page configured (project settings → notionParentPageId)', {
        retryable: false,
      });
    }
    const marker = idempotencyMarker(ctx);
    // Find-before-create: our pages end with a marker paragraph; search by title then verify.
    for (const page of await notion.search(input.title, 10)) {
      if (NotionClient.pageTitle(page) !== input.title || page.archived || page.in_trash) continue;
      const blocks = await notion.listBlocks(page.id);
      if (JSON.stringify(blocks.slice(-3)).includes(marker)) {
        return {
          output: { pageId: page.id, url: page.url, title: input.title, created: false },
          summary: `Notion page "${input.title}" already published`,
          externalResources: [{ provider: 'NOTION', type: 'NOTION_PAGE', externalId: page.id, title: input.title, url: page.url }],
        };
      }
    }
    const page = await notion.createPage({
      parentPageId,
      parentDatabaseId: input.parentDatabaseId,
      title: input.title,
      markdown: `${input.markdown}\n\n---\n_Generated by ${BRAND.name} · ${marker}_`,
      icon: input.icon,
    });
    return {
      output: { pageId: page.id, url: page.url, title: input.title, created: true },
      summary: `Published "${input.title}" to Notion`,
      externalResources: [{ provider: 'NOTION', type: 'NOTION_PAGE', externalId: page.id, title: input.title, url: page.url }],
    };
  },
  async compensate(_input, output, ctx) {
    if (!output.created) return { summary: 'Page pre-existed; left untouched' };
    const notion = await ctx.clients.notion();
    await notion.archivePage(output.pageId);
    return { summary: `Archived Notion page ${output.title}` };
  },
  async simulate(input, ctx) {
    return {
      simulated: true,
      output: { pageId: `demo-${ctx.idempotencyKey}`, url: null, title: input.title, created: true },
      summary: `[Simulated] Published "${input.title}" to Notion`,
      externalResources: [{ provider: 'NOTION', type: 'NOTION_PAGE', externalId: `demo-${ctx.idempotencyKey}`, title: input.title }],
    };
  },
});

export const notionUpdatePage = defineTool({
  name: 'notion.updatePage',
  title: 'Update Notion page',
  description: 'Replace the content (and optionally title) of a Notion page.',
  category: 'notion',
  provider: 'NOTION',
  agent: 'docs',
  inputSchema: z.object({ pageId: z.string().min(1), title: z.string().max(200).optional(), markdown: z.string().min(1).max(500_000) }),
  permission: 'docs:write',
  risk: 'write',
  sideEffects: true,
  async execute(input, ctx) {
    const notion = await ctx.clients.notion();
    if (input.title) await notion.updatePageTitle(input.pageId, input.title);
    await notion.replaceContent(input.pageId, input.markdown);
    const page = await notion.getPage(input.pageId);
    return { output: { pageId: page.id, url: page.url }, summary: `Updated Notion page ${NotionClient.pageTitle(page)}` };
  },
  async simulate(input) {
    return { simulated: true, output: { pageId: input.pageId, url: null }, summary: '[Simulated] Updated Notion page' };
  },
});

export const notionAppendToPage = defineTool({
  name: 'notion.appendBlocks',
  title: 'Append to Notion page',
  description: 'Append Markdown content to an existing Notion page.',
  category: 'notion',
  provider: 'NOTION',
  inputSchema: z.object({ pageId: z.string().min(1), markdown: z.string().min(1).max(200_000) }),
  permission: 'docs:write',
  risk: 'write',
  sideEffects: true,
  async execute(input, ctx) {
    const notion = await ctx.clients.notion();
    const marker = idempotencyMarker(ctx);
    const blocks = await notion.listBlocks(input.pageId);
    if (JSON.stringify(blocks).includes(marker))
      return { output: { pageId: input.pageId, appended: false }, summary: 'Content already appended' };
    await notion.appendMarkdown(input.pageId, `${input.markdown}\n\n_${marker}_`);
    return { output: { pageId: input.pageId, appended: true }, summary: 'Appended content to Notion page' };
  },
});

export const notionSearchPages = defineTool({
  name: 'notion.searchPages',
  title: 'Search Notion',
  description: 'Search Notion pages shared with the integration.',
  category: 'notion',
  provider: 'NOTION',
  inputSchema: z.object({ query: z.string().max(200).default('') }),
  permission: 'knowledge:read',
  risk: 'read',
  sideEffects: false,
  async execute(input, ctx) {
    const notion = await ctx.clients.notion();
    const pages = await notion.search(input.query);
    const items = pages.map((p) => ({ id: p.id, title: NotionClient.pageTitle(p), url: p.url, lastEdited: p.last_edited_time ?? null }));
    return { output: { items }, summary: `${items.length} Notion page(s)` };
  },
});

export const notionGetPage = defineTool({
  name: 'notion.getPage',
  title: 'Read Notion page',
  description: 'Retrieve a Notion page as Markdown.',
  category: 'notion',
  provider: 'NOTION',
  inputSchema: z.object({ pageId: z.string().min(1) }),
  permission: 'knowledge:read',
  risk: 'read',
  sideEffects: false,
  async execute(input, ctx) {
    const notion = await ctx.clients.notion();
    const page = await notion.getPageMarkdown(input.pageId);
    return { output: page, summary: `Read "${page.title}"` };
  },
});

export const notionTools: AnySdlcTool[] = [notionCreatePage, notionUpdatePage, notionAppendToPage, notionSearchPages, notionGetPage];
